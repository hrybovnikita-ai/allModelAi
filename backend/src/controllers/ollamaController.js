const ollamaAdapter = require('../services/ollama/ollamaAdapter');
const ollamaCloud = require('../services/ollama/ollamaCloudConfig');

async function getOllamaStatus(req, res) {
    const cloud = await ollamaCloud.listOllamaCloudModels();
    const local = await ollamaAdapter.checkConnection();
    const localOnline = Boolean(local?.online);
    const cloudOnline = Boolean(cloud.online);
    const payload = {
        online: cloudOnline || localOnline,
        cloud: {
            online: cloudOnline,
            configured: ollamaCloud.isOllamaCloudConfigured(),
            baseUrl: ollamaCloud.getOllamaCloudBaseUrl(),
            models: cloud.models || [],
            message: cloud.message,
        },
        local,
        prefer: ollamaCloud.isOllamaCloudConfigured() ? 'cloud' : 'local',
    };
    const ok = payload.cloud.configured || localOnline;
    return res.status(ok ? 200 : 503).json(payload);
}

async function postOllamaChat(req, res) {
    try {
        const model = String(req.body?.model || '').trim();
        const messages = Array.isArray(req.body?.messages) ? req.body.messages : [];
        const mode = String(req.body?.mode || 'auto').toLowerCase();
        if (!model) return res.status(400).json({ message: 'model is required' });
        if (!messages.length) return res.status(400).json({ message: 'messages are required' });

        const useCloud = mode === 'cloud'
            || (mode === 'auto' && ollamaCloud.isOllamaCloudConfigured());
        if (useCloud) {
            if (!ollamaCloud.isOllamaCloudConfigured()) {
                return res.status(503).json({
                    message: 'Ollama Cloud is not configured. Set OLLAMA_API_KEY on the backend.',
                    code: 'OLLAMA_CLOUD_NOT_CONFIGURED',
                });
            }
            if (!ollamaCloud.isAllowedOllamaCloudModel(model)) {
                return res.status(400).json({
                    message: 'Unknown Ollama Cloud model id.',
                    code: 'OLLAMA_CLOUD_MODEL_NOT_ALLOWED',
                });
            }
            const response = await fetch(ollamaCloud.ollamaCloudChatCompletionsUrl(), {
                method: 'POST',
                headers: {
                    Authorization: `Bearer ${ollamaCloud.getOllamaApiKey()}`,
                    'Content-Type': 'application/json',
                },
                signal: AbortSignal.timeout(Number(process.env.OLLAMA_CHAT_TIMEOUT_MS || 120_000)),
                body: JSON.stringify({
                    model,
                    messages,
                    stream: false,
                }),
            });
            const data = await response.json().catch(() => ({}));
            if (!response.ok) {
                const mapped = ollamaCloud.mapOllamaCloudHttpError(
                    response.status,
                    data?.error?.message || data?.message || '',
                );
                ollamaCloud.logOllamaCloudHttpError(response.status, data, { model });
                return res.status(mapped?.clientStatus || 502).json({
                    message: mapped?.message || 'Ollama Cloud chat failed',
                    code: mapped?.code || 'OLLAMA_CLOUD_CHAT_FAILED',
                    model,
                    provider: 'ollama_cloud',
                });
            }
            return res.json({
                text: data?.choices?.[0]?.message?.content || '',
                model: data?.model || model,
                provider: 'ollama_cloud',
                local: false,
                note: 'Response generated by Ollama Cloud. This is not an OpenAI GPT-4.1 Mini response.',
            });
        }

        const result = await ollamaAdapter.generateChat({
            model,
            messages,
            stream: false,
        });
        return res.json({
            ...result,
            note: 'Local model responses still consume your device resources (CPU/GPU/electricity).',
        });
    } catch (error) {
        return res.status(error.status || 502).json({
            message: error.message || 'Ollama chat failed',
            code: error.code || 'OLLAMA_CHAT_FAILED',
        });
    }
}

module.exports = {
    getOllamaStatus,
    postOllamaChat,
};
